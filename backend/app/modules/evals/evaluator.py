import logging
import math
import time
from typing import Any

from app.modules.connections.registry import DatabaseConnectionSpec
from app.modules.evals.golden_dataset import GoldenTestCase
from app.modules.execution.executor import ExecutionResult, SQLExecutor
from app.modules.security.gate import SecurityGate
from app.schemas.evals import EvalCaseResult

logger = logging.getLogger(__name__)


def _normalize_value(val: Any) -> Any:
    """Normalize cells for semantic comparison across SQL variations."""
    if val is None:
        return None
    if isinstance(val, (int, bool)):
        return val
    if isinstance(val, (float,)):
        return round(val, 2)
    if isinstance(val, str):
        cleaned = val.strip().lower()
        try:
            # If string is numeric, normalize float
            num = float(cleaned)
            return round(num, 2)
        except ValueError:
            return cleaned
    return str(val).strip().lower()


def _rows_match(candidate_rows: list[dict[str, Any]], golden_rows: list[dict[str, Any]]) -> bool:
    """Compare two result sets regardless of column aliases, with numeric tolerance."""
    if len(candidate_rows) != len(golden_rows):
        return False
    if not candidate_rows and not golden_rows:
        return True

    # Check row-by-row matching of values
    for cand_row, gold_row in zip(candidate_rows, golden_rows, strict=False):
        cand_vals = sorted([_normalize_value(v) for v in cand_row.values()], key=lambda x: str(x))
        gold_vals = sorted([_normalize_value(v) for v in gold_row.values()], key=lambda x: str(x))

        if len(cand_vals) != len(gold_vals):
            return False

        for c, g in zip(cand_vals, gold_vals, strict=False):
            if c != g:
                # Handle subtle float delta
                if isinstance(c, (int, float)) and isinstance(g, (int, float)):
                    if not math.isclose(float(c), float(g), abs_tol=0.05):
                        return False
                else:
                    return False
    return True


def evaluate_test_case(
    *,
    case: GoldenTestCase,
    candidate_sql: str | None,
    spec: DatabaseConnectionSpec,
    gate: SecurityGate,
    executor: SQLExecutor,
) -> EvalCaseResult:
    """Evaluate candidate SQL against a canonical golden test case on live PostgreSQL."""
    start_time = time.perf_counter()

    # 1. Execute Golden SQL to establish ground truth
    golden_val = gate.validate(
        case.golden_sql,
        allowed_schemas=spec.target_schemas,
        max_rows=spec.max_rows,
    )
    if not golden_val.passed or golden_val.validated_sql is None:
        return EvalCaseResult(
            case_id=case.id,
            question=case.question,
            difficulty=case.difficulty,
            category=case.category,
            status="error",
            vast_passed=False,
            execution_accuracy=False,
            golden_sql=case.golden_sql,
            generated_sql=candidate_sql,
            golden_row_count=0,
            latency_ms=0.0,
            error_message="Golden SQL failed internal AST validation.",
        )

    golden_exec = executor.execute(golden_val.validated_sql, spec, include_explain=False)
    if golden_exec.status != "success":
        return EvalCaseResult(
            case_id=case.id,
            question=case.question,
            difficulty=case.difficulty,
            category=case.category,
            status="error",
            vast_passed=True,
            execution_accuracy=False,
            golden_sql=case.golden_sql,
            generated_sql=candidate_sql,
            golden_row_count=0,
            latency_ms=0.0,
            error_message=f"Golden SQL failed execution: {golden_exec.error_message}",
        )

    # 2. Check Candidate SQL presence
    if not candidate_sql or not candidate_sql.strip():
        elapsed_ms = (time.perf_counter() - start_time) * 1000
        return EvalCaseResult(
            case_id=case.id,
            question=case.question,
            difficulty=case.difficulty,
            category=case.category,
            status="error",
            vast_passed=False,
            execution_accuracy=False,
            golden_sql=case.golden_sql,
            generated_sql=None,
            golden_row_count=golden_exec.row_count,
            candidate_row_count=0,
            latency_ms=round(elapsed_ms, 2),
            error_message="No SQL query generated by model.",
        )

    # 3. Validate Candidate SQL via deterministic AST gate
    val = gate.validate(
        candidate_sql,
        allowed_schemas=spec.target_schemas,
        max_rows=spec.max_rows,
    )
    if not val.passed or val.validated_sql is None:
        elapsed_ms = (time.perf_counter() - start_time) * 1000
        violation_summary = "; ".join(val.violations) if val.violations else "Security Gate rejected query."
        return EvalCaseResult(
            case_id=case.id,
            question=case.question,
            difficulty=case.difficulty,
            category=case.category,
            status="blocked",
            vast_passed=False,
            execution_accuracy=False,
            golden_sql=case.golden_sql,
            generated_sql=candidate_sql,
            golden_row_count=golden_exec.row_count,
            candidate_row_count=0,
            latency_ms=round(elapsed_ms, 2),
            error_message=violation_summary,
        )

    # 4. Execute Candidate SQL against PostgreSQL 16
    cand_exec: ExecutionResult = executor.execute(
        val.validated_sql,
        spec,
        include_explain=False,
    )
    elapsed_ms = (time.perf_counter() - start_time) * 1000

    if cand_exec.status != "success":
        return EvalCaseResult(
            case_id=case.id,
            question=case.question,
            difficulty=case.difficulty,
            category=case.category,
            status="error",
            vast_passed=True,
            execution_accuracy=False,
            golden_sql=case.golden_sql,
            generated_sql=candidate_sql,
            golden_row_count=golden_exec.row_count,
            candidate_row_count=0,
            latency_ms=round(elapsed_ms, 2),
            error_message=cand_exec.error_message or "Execution failed on database.",
        )

    # 5. Semantic Result Set Equivalence (Execution Accuracy)
    matches = _rows_match(cand_exec.rows, golden_exec.rows)
    return EvalCaseResult(
        case_id=case.id,
        question=case.question,
        difficulty=case.difficulty,
        category=case.category,
        status="passed" if matches else "mismatch",
        vast_passed=True,
        execution_accuracy=matches,
        golden_sql=case.golden_sql,
        generated_sql=candidate_sql,
        golden_row_count=golden_exec.row_count,
        candidate_row_count=cand_exec.row_count,
        latency_ms=round(elapsed_ms, 2),
        error_message=None if matches else (
            f"Returned {cand_exec.row_count} row(s), expected {golden_exec.row_count} matching ground truth."
        ),
    )

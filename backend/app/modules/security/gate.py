from collections.abc import Sequence

import sqlglot
from sqlglot import exp
from sqlglot.errors import ParseError

from app.modules.security.policies import (
    ALLOWED_ROOT_EXPRESSION_TYPES,
    BLOCKED_FUNCTION_NAMES,
    BLOCKED_FUNCTION_PREFIXES,
    BLOCKED_UNQUALIFIED_TABLE_PREFIXES,
    BLOCKED_UNQUALIFIED_TABLES,
    FORBIDDEN_AST_EXPRESSION_TYPES,
    MAX_SQL_LENGTH,
)
from app.modules.security.types import (
    SecurityRuleCheck,
    SecurityValidationResult,
    mint_validated_sql,
)


def _extract_function_name(node: exp.Expression) -> str | None:
    if isinstance(node, exp.Anonymous):
        return (node.name or "").strip().lower() or None
    if isinstance(node, exp.Func):
        return (node.sql_name() or node.name or "").strip().lower() or None
    return None


def _is_blocked_function(func_name: str) -> bool:
    if func_name in BLOCKED_FUNCTION_NAMES:
        return True
    return any(func_name.startswith(prefix) for prefix in BLOCKED_FUNCTION_PREFIXES)


def _is_blocked_unqualified_table(table_name: str) -> bool:
    if table_name in BLOCKED_UNQUALIFIED_TABLES:
        return True
    return any(table_name.startswith(prefix) for prefix in BLOCKED_UNQUALIFIED_TABLE_PREFIXES)


def _has_wildcard_projection(root: exp.Expression) -> bool:
    """Detect SELECT * or SELECT alias.* via AST without flagging COUNT(*)."""
    return any(
        isinstance(star.parent, (exp.Select, exp.Column)) for star in root.find_all(exp.Star)
    )


def _is_valid_query_tree_root(node: exp.Expression) -> bool:
    if isinstance(node, exp.Select):
        return True
    if isinstance(node, (exp.Union, exp.Intersect, exp.Except)):
        left = node.this
        right = node.expression
        return (
            isinstance(left, exp.Expression)
            and isinstance(right, exp.Expression)
            and _is_valid_query_tree_root(left)
            and _is_valid_query_tree_root(right)
        )
    return False


def _set_limit_value(root: exp.Expression, limit_value: int) -> None:
    existing_limit = root.args.get("limit")
    if isinstance(existing_limit, exp.Fetch):
        existing_limit.set("count", exp.Literal.number(limit_value))
    elif isinstance(existing_limit, exp.Limit):
        existing_limit.set("expression", exp.Literal.number(limit_value))
    else:
        root.set("limit", exp.Limit(expression=exp.Literal.number(limit_value)))


def _enforce_limit(root: exp.Expression, ceiling: int) -> tuple[int, bool, bool]:
    """Deterministically enforce or clamp a top-level LIMIT ceiling on the AST."""
    existing_limit = root.args.get("limit")

    if existing_limit is None:
        root.set("limit", exp.Limit(expression=exp.Literal.number(ceiling)))
        return ceiling, True, False

    if isinstance(existing_limit, exp.Limit):
        limit_expr = existing_limit.expression
        if isinstance(limit_expr, exp.Literal) and limit_expr.is_int:
            requested = int(limit_expr.this)
            if 1 <= requested <= ceiling:
                return requested, False, False
            clamped = max(1, min(requested, ceiling))
            existing_limit.set("expression", exp.Literal.number(clamped))
            return clamped, False, True

        # Non-integer / dynamic / ALL limits are replaced with the strict ceiling.
        root.set("limit", exp.Limit(expression=exp.Literal.number(ceiling)))
        return ceiling, False, True

    if isinstance(existing_limit, exp.Fetch):
        count_expr = existing_limit.args.get("count")
        if isinstance(count_expr, exp.Literal) and count_expr.is_int:
            requested = int(count_expr.this)
            if 1 <= requested <= ceiling:
                return requested, False, False
            clamped = max(1, min(requested, ceiling))
            existing_limit.set("count", exp.Literal.number(clamped))
            return clamped, False, True

        root.set("limit", exp.Limit(expression=exp.Literal.number(ceiling)))
        return ceiling, False, True

    root.set("limit", exp.Limit(expression=exp.Literal.number(ceiling)))
    return ceiling, False, True


class SecurityGate:
    """100% deterministic SQLGlot AST security validator for PostgreSQL queries.

    Never depends on LLM compliance. Every SQL statement—whether generated by
    AI or edited in Monaco—must pass through this gate before execution.
    """

    def validate(
        self,
        sql: str,
        *,
        allowed_schemas: Sequence[str],
        max_rows: int = 200,
        hard_max_rows: int = 1000,
    ) -> SecurityValidationResult:
        checks: list[SecurityRuleCheck] = []
        violations: list[str] = []

        stripped = sql.strip()
        if not stripped:
            violations.append("SQL query cannot be empty.")
            checks.append(SecurityRuleCheck("non_empty", False, "Empty SQL input."))
            return SecurityValidationResult(False, None, tuple(violations), tuple(checks))

        if len(stripped) > MAX_SQL_LENGTH:
            violations.append(f"SQL query exceeds maximum length of {MAX_SQL_LENGTH} characters.")
            checks.append(
                SecurityRuleCheck(
                    "max_length",
                    False,
                    f"Length {len(stripped)} exceeds {MAX_SQL_LENGTH}.",
                )
            )
            return SecurityValidationResult(False, None, tuple(violations), tuple(checks))
        checks.append(SecurityRuleCheck("non_empty", True, "Query present and within size limit."))

        # 1. Deterministic PostgreSQL AST parsing
        try:
            parsed = sqlglot.parse(stripped, read="postgres")
        except ParseError as exc:
            violations.append(f"SQL syntax could not be parsed safely: {exc}")
            checks.append(SecurityRuleCheck("ast_parse", False, "PostgreSQL AST parse failed."))
            return SecurityValidationResult(False, None, tuple(violations), tuple(checks))

        # Ignore harmless empty trailing semicolon/comment placeholders while strictly
        # blocking every real multi-statement batch.
        statements = [
            stmt for stmt in parsed if stmt is not None and not isinstance(stmt, exp.Semicolon)
        ]
        if len(statements) != 1:
            violations.append(
                f"Expected exactly 1 SQL statement; found {len(statements)} "
                "(multi-statement batches are prohibited)."
            )
            checks.append(
                SecurityRuleCheck(
                    "single_statement",
                    False,
                    f"Found {len(statements)} statements.",
                )
            )
            return SecurityValidationResult(False, None, tuple(violations), tuple(checks))
        checks.append(SecurityRuleCheck("single_statement", True, "Single statement verified."))

        root = statements[0]

        # 2. Strict root statement allowlist
        if not isinstance(root, ALLOWED_ROOT_EXPRESSION_TYPES) or not _is_valid_query_tree_root(
            root
        ):
            violations.append(
                f"Only read-only SELECT queries are permitted; found '{type(root).__name__}'."
            )
            checks.append(
                SecurityRuleCheck(
                    "readonly_root",
                    False,
                    f"Disallowed root expression '{type(root).__name__}'.",
                )
            )
            return SecurityValidationResult(False, None, tuple(violations), tuple(checks))
        checks.append(SecurityRuleCheck("readonly_root", True, "Read-only SELECT root verified."))

        # 3. Walk complete AST for forbidden statements, writable CTEs, locks, SELECT INTO
        forbidden_found: list[str] = []
        for node in root.walk():
            if isinstance(node, FORBIDDEN_AST_EXPRESSION_TYPES):
                forbidden_found.append(type(node).__name__)
        if forbidden_found:
            unique_forbidden = sorted(set(forbidden_found))
            violations.append(
                "Query contains prohibited write, DDL, locking, or administrative "
                f"constructs: {', '.join(unique_forbidden)}."
            )
            checks.append(
                SecurityRuleCheck(
                    "no_forbidden_constructs",
                    False,
                    f"Blocked constructs: {', '.join(unique_forbidden)}.",
                )
            )
        else:
            checks.append(
                SecurityRuleCheck(
                    "no_forbidden_constructs",
                    True,
                    "No DDL, DML, writable CTEs, locking, or administrative nodes.",
                )
            )

        # 4. Block dangerous PostgreSQL system, file, network, and DoS functions
        blocked_funcs: list[str] = []
        for node in root.walk():
            func_name = _extract_function_name(node)
            if func_name and _is_blocked_function(func_name):
                blocked_funcs.append(func_name)
        if blocked_funcs:
            unique_funcs = sorted(set(blocked_funcs))
            violations.append(
                f"Query invokes prohibited PostgreSQL function(s): {', '.join(unique_funcs)}."
            )
            checks.append(
                SecurityRuleCheck(
                    "safe_functions",
                    False,
                    f"Blocked function(s): {', '.join(unique_funcs)}.",
                )
            )
        else:
            checks.append(
                SecurityRuleCheck("safe_functions", True, "No prohibited system functions.")
            )

        # 5. Enforce schema and table allowlist
        allowed_schema_set = {schema.strip().lower() for schema in allowed_schemas if schema}
        cte_names = {
            cte.alias_or_name.strip().lower() for cte in root.find_all(exp.CTE) if cte.alias_or_name
        }
        schema_violations: list[str] = []
        for table in root.find_all(exp.Table):
            catalog = (table.catalog or "").strip().lower()
            schema_name = (table.db or "").strip().lower()
            table_name = (table.name or "").strip().lower()

            if catalog:
                schema_violations.append(
                    f"Cross-database reference '{catalog}.{schema_name}.{table_name}' is blocked."
                )
                continue

            if schema_name:
                if schema_name not in allowed_schema_set:
                    schema_violations.append(
                        f"Access to schema '{schema_name}' is not permitted "
                        f"(allowed: {', '.join(sorted(allowed_schema_set))})."
                    )
            elif (
                table_name
                and table_name not in cte_names
                and _is_blocked_unqualified_table(table_name)
            ):
                schema_violations.append(
                    f"Access to restricted table '{table_name}' is prohibited."
                )

        if schema_violations:
            violations.extend(sorted(set(schema_violations)))
            checks.append(
                SecurityRuleCheck(
                    "schema_isolation",
                    False,
                    "; ".join(sorted(set(schema_violations))),
                )
            )
        else:
            checks.append(
                SecurityRuleCheck(
                    "schema_isolation",
                    True,
                    f"All table references stay within allowed schema(s): "
                    f"{', '.join(sorted(allowed_schema_set))}.",
                )
            )

        if violations:
            return SecurityValidationResult(False, None, tuple(violations), tuple(checks))

        # 6. Deterministic row-limit ceiling enforcement
        ceiling = max(1, min(max_rows, hard_max_rows))
        has_select_star = _has_wildcard_projection(root)
        enforced_limit, was_injected, was_clamped = _enforce_limit(root, ceiling)
        limit_detail = (
            f"Injected LIMIT {enforced_limit}."
            if was_injected
            else f"Clamped LIMIT to {enforced_limit}."
            if was_clamped
            else f"Preserved safe LIMIT {enforced_limit}."
        )
        checks.append(SecurityRuleCheck("row_limit_ceiling", True, limit_detail))

        normalized_sql = root.sql(dialect="postgres")
        if was_injected or was_clamped:
            # Probe one extra row beyond enforced_limit so SQLExecutor detects
            # exact truncation without false positives on exact-boundary tables.
            probe_ast = root.copy()
            _set_limit_value(probe_ast, enforced_limit + 1)
            execution_sql = probe_ast.sql(dialect="postgres")
        else:
            execution_sql = normalized_sql

        validated = mint_validated_sql(
            original_sql=stripped,
            normalized_sql=normalized_sql,
            execution_sql=execution_sql,
            enforced_limit=enforced_limit,
            limit_was_injected=was_injected,
            limit_was_clamped=was_clamped,
            has_select_star=has_select_star,
            checks=tuple(checks),
        )
        return SecurityValidationResult(True, validated, (), tuple(checks))
